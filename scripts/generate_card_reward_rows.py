"""Generate reviewed resource-row card gates, independently of HP and combat lifecycle.

The receipt is policy plus resource evidence, not an inferred MMO+0x19 meaning.
Normal regeneration requires no client. --client-root checks the original inputs.
"""
from pathlib import Path
import argparse, hashlib, json, re
ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'release/components/cards/card_reward_rows.json'
OUTPUT = ROOT / 'release/components/cards/card_reward_row_data.inc'

def generate(receipt):
    if receipt['schema'] != 1 or receipt['runtime_acceptance'] is not False:
        raise ValueError('unexpected reviewed policy schema')
    csv = ROOT / 'release/components/cards/card_drop_cn.csv'
    if hashlib.sha256(csv.read_bytes()).hexdigest().upper() != receipt['card_csv_sha256']:
        raise ValueError('card CSV changed: review resource-row coverage')
    resources, rows, seen = [], [], set()
    for r in sorted(receipt['resources'], key=lambda x: x['resource']):
        name = r['resource']
        if name in seen or not re.fullmatch(r'[a-z0-9_]+\.mmo', name):
            raise ValueError('duplicate or invalid resource')
        seen.add(name)
        denied, all_rewards = r['deny_card_rows'], r['deny_all_rows']
        if denied != sorted(set(denied)) or not set(all_rewards) <= set(denied):
            raise ValueError('invalid row policy')
        authored = {x['row']: x for x in r['rows']}
        if len(authored) != len(r['rows']) or not 0 < r['record_count'] <= 65536:
            raise ValueError('invalid reviewed record bounds')
        for row in denied:
            x = authored[row]
            if not 0 <= row < r['record_count'] or x['hp'] <= 0 or not x['card_denied']:
                raise ValueError('policy outside positive-HP reviewed rows')
        if not denied:
            continue
        resources.append('    {"%s",%du,%du,%du},' % (name, len(rows), len(denied), r['record_count']))
        rows += [(row, 2 if row in all_rewards else 1) for row in denied]
    text = ['/* Generated by scripts/generate_card_reward_rows.py; do not hand-edit. */',
            '#ifndef CARD_REWARD_ROW_DATA_INC', '#define CARD_REWARD_ROW_DATA_INC',
            '#define CARD_REWARD_RESOURCE_COUNT %du' % len(resources),
            '#define CARD_REWARD_ROW_COUNT %du' % len(rows),
            'struct card_reward_resource_def { const char *name; unsigned first, count, record_count; };',
            'struct card_reward_row_def { unsigned short row; unsigned char policy; };',
            'static const struct card_reward_resource_def card_reward_resources[CARD_REWARD_RESOURCE_COUNT] = {',
            *resources, '};',
            'static const struct card_reward_row_def card_reward_rows[CARD_REWARD_ROW_COUNT] = {',
            *['    {%du,%du},' % x for x in rows], '};', '#endif', '']
    return '\n'.join(text)

def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--client-root', type=Path)
    args = ap.parse_args()
    receipt = json.loads(SOURCE.read_text('utf-8'))
    if args.client_root:
        import lumineos_codec as codec
        import struct
        import generate_cn_card_drops as cn
        names = {name for _, name in cn.load_pools() if name.endswith('.mmo')}
        mixed, parsed = set(), 0
        for name in sorted(names):
            raw = (args.client_root / 'flying/mmo' / name).read_bytes()
            _, records, _ = codec.mmo_model(raw, args.client_root, False)
            parsed += 1
            positive = [m for m, _ in records if struct.unpack_from('<i', m, 8)[0] > 0 and m[24] != 4]
            if any(m[25] for m in positive) and any(not m[25] for m in positive):
                mixed.add(name)
        if parsed != receipt['scan']['card_pool_mmo_resources'] or mixed != {r['resource'] for r in receipt['resources']}:
            raise ValueError('shared-resource coverage changed: review new or missing mixed resources')
        for r in receipt['resources']:
            raw = (args.client_root / 'flying/mmo' / r['resource']).read_bytes()
            if hashlib.sha256(raw).hexdigest().upper() != r['sha256']:
                raise ValueError('resource hash changed: ' + r['resource'])
            _, records, _ = codec.mmo_model(raw, args.client_root, False)
            if len(records) != r['record_count']:
                raise ValueError('row count changed')
            for x in r['rows']:
                mem = records[x['row']][0]
                if (struct.unpack_from('<i', mem, 8)[0], struct.unpack_from('<i', mem)[0], mem[24], mem[25], mem[26], mem[66:130].split(b'\0',1)[0].decode('ascii'), mem[412:476].split(b'\0',1)[0].decode('ascii')) != (x['hp'], x['object_id'], x['target_type'], x['field19'], x['reward_kind'], x['clash'], x['deform']):
                    raise ValueError('reviewed row changed')
    data = generate(receipt).encode('utf-8')
    if args.check:
        if OUTPUT.read_bytes() != data:
            raise ValueError('generated policy is stale')
    else:
        OUTPUT.write_bytes(data)
    print('CARD_REWARD_ROWS_PASS resources=%d denied_rows=%d runtime_acceptance=false' %
          (sum(bool(r['deny_card_rows']) for r in receipt['resources']), sum(len(r['deny_card_rows']) for r in receipt['resources'])))

if __name__ == '__main__':
    main()
